#include <string>
#include <vector>

void integer_sqrt() {
    int n = 50;
    int root = 0;
    while ((root + 1) * (root + 1) <= n) root += 1;
    (void)root;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void power_of_two() {
    unsigned int n = 64u;
    bool is_power = (n != 0u) && ((n & (n - 1u)) == 0u);
    (void)is_power;
}

void reverse_digits() {
    int n = 12345;
    int reversed = 0;
    while (n > 0) {
        reversed = reversed * 10 + (n % 10);
        n /= 10;
    }
    (void)reversed;
}

extern "C" int amber_spruce();
extern "C" void still_haven();
extern "C" void placid_quartz();
extern "C" void prime_bridge();
extern "C" void calm_harbor();

int main() {
    integer_sqrt();
    text_contains();
    power_of_two();
    reverse_digits();
    still_haven();
    placid_quartz();
    prime_bridge();
    calm_harbor();
    return amber_spruce();
}
